"""
Turn the human-eval items into a Google Apps Script that builds the Google Form.

    python src/detection/make_google_form.py

Then:
  1. Open https://script.google.com  ->  New project
  2. Delete the placeholder code, paste the contents of
     results/detection/human_eval/google_form_script.gs
  3. Click Run (allow the permissions prompt: it only creates a form in your Drive)
  4. The Execution log shows the link to share and the edit link. The editable form is also
     saved in your Google Drive as "Real or generated? (DSS5105 Track 3)".

The question titles are "Item 01" ... "Item 12", so the downloaded responses
CSV works directly with:  python src/detection/human_eval.py score responses.csv
"""

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "results" / "detection" / "human_eval"

def intro(n):
    return (
        f"There are {n} short paragraphs on this page (about 70-130 words each). Each one either comes "
        "from a published EMNLP 2025 research paper or was generated by an LLM for our class project. "
        "All are about using LLMs as judges, and citations were removed from all of them.\n\n"
        f"For each paragraph, answer 3 questions ({3 * n} in total, plus your name):\n"
        "1. Real paper or Generated?\n"
        "2. How confident are you? (1 = guess, 5 = certain)\n"
        "3. What helped you with your decision? (a few words is enough)\n\n"
        f"It takes about {round(n * 1.25)}-{round(n * 1.5)} minutes. Go with your first impression and "
        "please don't search for the text online."
    )


def main():
    key = pd.read_csv(OUT / "PRIVATE_answer_key.csv")
    items = [{"id": r.item_id, "text": r.text} for r in key.itertuples()]
    js = f"""// Auto-generated by src/detection/make_google_form.py. Paste into script.google.com and click Run.
function buildForm() {{
  var items = {json.dumps(items, ensure_ascii=False, indent=2)};
  var form = FormApp.create('Real or generated? (DSS5105 Track 3)');
  form.setDescription({json.dumps(intro(len(items)))});
  form.setCollectEmail(false);
  form.setShuffleQuestions(false);
  form.addTextItem().setTitle('Your name or initials').setRequired(true);
  for (var i = 0; i < items.length; i++) {{
    var it = items[i];
    form.addMultipleChoiceItem()
        .setTitle(it.id)
        .setHelpText(it.text)
        .setChoiceValues(['Real paper', 'Generated'])
        .setRequired(true);
    form.addScaleItem()
        .setTitle('Confidence (' + it.id + ')')
        .setBounds(1, 5)
        .setLabels('Guess', 'Certain')
        .setRequired(true);
    form.addTextItem()
        .setTitle('What helped you with your decision? (' + it.id + ')')
        .setRequired(true);
  }}
  Logger.log('Share this link with raters: ' + form.getPublishedUrl());
  Logger.log('Edit link (keep private, opens the editable form): ' + form.getEditUrl());
}}
"""
    path = OUT / "google_form_script.gs"
    path.write_text(js, encoding="utf-8")
    print(f"Wrote {path} ({len(items)} items)")
    print("Next: script.google.com -> New project -> paste -> Run -> check the log for the share link.")


if __name__ == "__main__":
    main()
